#!/usr/bin/env python3
"""Generate crates/rusty7800-core/src/palette.rs from a7800.cpp palette tables.

Re-run:  python3 scripts/gen_palette.py ../../a7800-5.2/src/mame/drivers/a7800.cpp ../crates/rusty7800-core/src/palette.rs
Verifies: each of the 6 palettes expands to exactly 256 entries (16 hues x 16 luminances).
Note: C++ declares [256*3] (768 pens); only the first 256 are initialized, the
rest are zero-filled. The Rust tables store the 256 defined pens; PENS_TOTAL=768
documents the full MAME pen space (see palette.rs).
Source of truth: a7800-5.2/src/mame/drivers/a7800.cpp (A7800 5.2 fork).
"""
import re, sys
from pathlib import Path

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("../../a7800-5.2/src/mame/drivers/a7800.cpp")
DST = Path(sys.argv[2]) if len(sys.argv) > 2 else Path("../crates/rusty7800-core/src/palette.rs")

text = SRC.read_text(encoding="utf-8", errors="replace")

# 1. Parse #define NAME \ ... blocks containing rgb_t(...)
defines: dict[str, list[tuple[int, int, int]]] = {}
for m in re.finditer(r"#define\s+(\w+)\s*\\\n((?:.*\\\n)*.*(?:\n|$))", text):
    name, body = m.group(1), m.group(2)
    # body continues until a line not ending in backslash
    lines = []
    for line in body.splitlines():
        lines.append(line)
        if not line.rstrip().endswith("\\"):
            break
    # NOTE: source contains a `0X51` (capital X) typo in NTSC_HUE9_PAL_HUE10_U2 — accept both.
    triples = re.findall(r"rgb_t\(\s*0[xX]([0-9A-Fa-f]+)\s*,\s*0[xX]([0-9A-Fa-f]+)\s*,\s*0[xX]([0-9A-Fa-f]+)", "\n".join(lines))
    if triples:
        defines[name] = [(int(r, 16), int(g, 16), int(b, 16)) for r, g, b in triples]

# 2. Parse the 6 palette arrays
palettes: dict[str, list[str]] = {}
for m in re.finditer(r"static const rgb_t\s+(\w+)\[256\*3\]\s*=\s*\{([^}]*)\}", text):
    name, body = m.group(1), m.group(2)
    refs = [w for w in re.findall(r"(\w+)", body) if w in defines]
    palettes[name] = refs

assert len(palettes) == 6, f"expected 6 palettes, got {list(palettes)}"
for name, refs in palettes.items():
    expanded = [c for r in refs for c in defines[r]]
    assert len(expanded) == 256, f"{name}: {len(expanded)} entries, expected 256"

order = ["a7800_palette", "a7800p_palette", "a7800u1_palette",
         "a7800pu1_palette", "a7800u2_palette", "a7800pu2_palette"]
rust_names = {"a7800_palette": "WARM_NTSC", "a7800p_palette": "WARM_PAL",
              "a7800u1_palette": "COOL_NTSC", "a7800pu1_palette": "COOL_PAL",
              "a7800u2_palette": "HOT_NTSC", "a7800pu2_palette": "HOT_PAL"}

out = []
out.append("//! Atari 7800 palettes for Rusty7800 — Phase 0 spec constants.")
out.append("//!")
out.append("//! GENERATED by `scripts/gen_palette.py` — do not hand-edit.")
out.append("//! Source of truth: `a7800-5.2/src/mame/drivers/a7800.cpp` (A7800 5.2).")
out.append("//! Each table = 16 hues x 16 luminances = 256 pens, literal RGB triplets.")
out.append("//! C++ declares `[256*3]` pens; initializers fill the first 256, the rest")
out.append("//! are zero-filled (black). `PENS_TOTAL` preserves that address space.")
out.append("")
out.append("/// Number of defined pens per palette (16 hues x 16 luminances).")
out.append("pub const PENS_DEFINED: usize = 256;")
out.append("/// Full MAME pen space per C++ `[256*3]` declaration; pens 256..768 are black.")
out.append("pub const PENS_TOTAL: usize = 768;")
out.append("")
for cpp in order:
    rn = rust_names[cpp]
    expanded = [c for r in palettes[cpp] for c in defines[r]]
    hue_list = ", ".join(palettes[cpp])
    out.append(f"/// `{cpp}` hues: {hue_list}.")
    out.append(f"pub const PALETTE_{rn}: [(u8, u8, u8); PENS_DEFINED] = [")
    for i in range(0, 256, 4):
        chunk = ", ".join(f"({r},{g},{b})" for r, g, b in expanded[i:i + 4])
        out.append(f"    {chunk},")
    out.append("];")
    out.append("")
out.append("/// One 256-pen palette table.")
out.append("pub type Palette = [(u8, u8, u8); PENS_DEFINED];")
out.append("/// All six palettes in (cpp_name, table) pairs.")
out.append("pub const ALL_PALETTES: [(&str, Palette); 6] = [")
for cpp in order:
    out.append(f'    ("{cpp}", PALETTE_{rust_names[cpp]}),')
out.append("];")
out.append("")
DST.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {DST} ({sum(len(v) for v in palettes.values())} hue refs -> 6x256 pens)")
