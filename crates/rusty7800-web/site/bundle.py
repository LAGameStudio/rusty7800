#!/usr/bin/env python3
"""Bundle the web shell into one double-clickable HTML file.

`site/index.html` + `site/app.js` + `site/pkg/rusty7800_web.{js,wasm}`
cannot run from `file://`: browsers block ES-module scripts and the
`fetch()` of the `.wasm` on the null origin (CORS). This script inlines
everything — glue JS as a classic script, the wasm as base64 decoded at
boot and passed straight to the initializer (no `fetch`, no modules, no
network at all) — into `site/rusty7800-standalone.html`, which runs from
disk, from any static host, and with any (or no) wasm MIME type::

    python3 site/bundle.py           # rebuild after wasm-pack
    python3 site/bundle.py --check   # CI: fail if the bundle is stale

Stdlib only. Re-run after `wasm-pack build ... --out-dir site/pkg`.
"""

import argparse
import base64
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GLUE = os.path.join(HERE, "pkg", "rusty7800_web.js")
WASM = os.path.join(HERE, "pkg", "rusty7800_web_bg.wasm")
APP = os.path.join(HERE, "app.js")
INDEX = os.path.join(HERE, "index.html")
OUT = os.path.join(HERE, "rusty7800-standalone.html")


def load(name: str) -> str:
    with open(name, encoding="utf-8") as f:
        return f.read()


def de_modularize(glue: str) -> str:
    """Turn wasm-pack `--target web` glue into a classic script.

    The glue is self-contained (no imports); only the `export`s and the
    `import.meta.url` fallback (unreached — we always pass bytes) tie it
    to modules. Anything unexpected aborts the bundle loudly.
    """
    out = []
    for line in glue.splitlines():
        if line.startswith("import "):
            raise SystemExit("bundle: unexpected import in glue JS")
        line = re.sub(r"^export (class|function|const|let|var|async function) ",
                      r"\1 ", line)
        m = re.match(r"^export \{(.*)\};$", line)
        if m:
            names = []
            for part in m.group(1).split(","):
                part = part.strip()
                if " as " in part:
                    src, alias = (p.strip() for p in part.split(" as "))
                    names.append(f"const {alias} = {src};"
                                 if alias != "default" else None)
                else:
                    names.append(None)
            out.extend(n for n in names if n)
            out.append("const init = __wbg_init;")
            continue
        out.append(line)
    text = "\n".join(out)
    # `import.meta` is a parse-time error in classic scripts: replace the
    # fetch fallback (dead — init() always receives bytes here) with a
    # loud error.
    text = text.replace(
        "module_or_path = new URL('rusty7800_web_bg.wasm', import.meta.url);",
        "throw new Error('standalone bundle: init() requires wasm bytes');",
    )
    if "import.meta" in text:
        # Only the fetch fallback references it; bytes are always passed.
        text += ("\n// NOTE: the import.meta.url fetch fallback above is dead in\n"
                 "// the bundle: init() always receives decoded bytes.\n")
    for want in ("class Emu", "function machine_list",
                 "function wasm_memory", "const init = __wbg_init;"):
        if want not in text:
            raise SystemExit(f"bundle: glue lost {want!r}; refusing")
    return text


def adapt_app(app: str) -> str:
    """Drop the module import (names are top-level now); surface errors."""
    lines = []
    for line in app.splitlines():
        if line.startswith("import "):
            lines.append("// (bundled: Emu/machine_list/wasm_memory are top-level)")
            continue
        lines.append(line)
    text = "\n".join(lines)
    if "import " in text or " from './pkg" in text:
        raise SystemExit("bundle: app.js still references the pkg module")
    # Route boot failures to the status line instead of a blank page.
    text = text.replace(
        "boot();",
        "boot().catch((e) => { $('status').textContent = 'boot failed: ' + e; throw e; });",
    )
    return text


def build() -> str:
    glue = de_modularize(load(GLUE))
    app = adapt_app(load(APP))
    with open(WASM, "rb") as f:
        b64 = base64.b64encode(f.read()).decode("ascii")
    index = load(INDEX)
    css = re.search(r"<style>(.*?)</style>", index, re.S).group(1)
    body = re.search(r"<body>(.*?)<script", index, re.S).group(1)
    return f"""<!doctype html>
<!-- GENERATED by site/bundle.py — do not edit. Regenerate after wasm-pack.
     Self-contained: no modules, no fetch, runs from file://. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Rusty7800 (web, standalone)</title>
<style>{css}</style>
</head>
<body>
{body}<script>
'use strict';
/* ---- wasm-pack glue (de-modularized) ---- */
{glue}
/* ---- wasm binary (base64, decoded at boot, never fetched) ---- */
const WASM_B64 = "{b64}";
function wasmBytes() {{
    const s = WASM_B64;
    const bin = atob(s);
    const out = new Uint8Array(bin.length);
    for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
    return out;
}}
/* ---- app shell (module import inlined above) ---- */
{app}
</script>
</body>
</html>
"""


def main() -> None:
    ap = argparse.ArgumentParser(description="bundle the web shell")
    ap.add_argument("--check", action="store_true",
                    help="fail if the checked-in bundle is stale")
    args = ap.parse_args()
    for p in (GLUE, WASM, APP, INDEX):
        if not os.path.exists(p):
            raise SystemExit(f"bundle: missing {p} (run wasm-pack first?)")
    # app.js boots with bare init(): point it at the embedded bytes via
    # the options object (a bare BufferSource trips the glue's deprecated
    # positional-parameter warning).
    html = build().replace(
        "await init();", "await init({ module_or_path: wasmBytes() });", 1
    )
    if args.check:
        if not os.path.exists(OUT) or load(OUT) != html:
            raise SystemExit("bundle: rusty7800-standalone.html is stale "
                             "(run site/bundle.py)")
        print("bundle fresh")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    print(f"wrote {OUT} ({os.path.getsize(OUT)} bytes)")


if __name__ == "__main__":
    if "--check" in sys.argv and not os.path.exists(OUT):
        raise SystemExit("bundle: rusty7800-standalone.html is stale "
                         "(run site/bundle.py)")
    main()
